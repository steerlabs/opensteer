/**
 * The lab behind each AI engine, so an engine can wear its provider's mark.
 * Null for an engine the product has not placed with a lab, which then wears
 * a neutral glyph rather than a monogram that pretends to be a brand.
 */
export function engineProviderId(driverKind: string): string | null {
  return harnessCatalogEntry(driverKind)?.brandProviderId ?? null;
}

/**
 * What a lab is called.
 *
 * The registry (`modelLabLabels`) is the one place the product names a lab, so
 * a lab this file has no logomark for is still named the way the registry
 * names it — "MiniMax", "OpenCode", "Z.ai" — rather than title-cased into
 * "Minimax". Title-casing is the last resort, for a provider id nobody has
 * named yet.
 */
export function providerLabel(providerId: string): string {
  const lab = modelLabLabels[providerId];
  if (lab) return lab;
  return providerId
    .split(/([._-])/u)
    .map((part) =>
      /^[._-]$/u.test(part) ? part : part.charAt(0).toLocaleUpperCase() + part.slice(1),
    )
    .join("");
}

interface ProviderLogoProps extends SVGProps<SVGSVGElement> {
  providerId: string;
}

/** The provider's logomark, or a monogram tile for unknown providers. */
export function ProviderLogo({ className, providerId, ...props }: ProviderLogoProps) {
  const brand = brands[providerId];
  const classes = className ? `provider-logo ${className}` : "provider-logo";
  if (!brand) {
    return (
      <svg aria-hidden className={classes} viewBox="0 0 24 24" {...props}>
        <rect fill="currentColor" height="21" opacity="0.16" rx="5.5" width="21" x="1.5" y="1.5" />
        <text
          dominantBaseline="central"
          fill="currentColor"
          fontFamily="inherit"
          fontSize="11"
          fontWeight="650"
          textAnchor="middle"
          x="12"
          y="12.5"
        >
          {providerLabel(providerId).charAt(0)}
        </text>
      </svg>
    );
  }
  return (
    <svg
      aria-hidden
      className={classes}
      fill="currentColor"
      viewBox={brand.viewBox ?? "0 0 24 24"}
      {...props}
    >
      {brand.path ? <path d={brand.path} /> : null}
      {brand.paths?.map((path, index) => (
        <path d={path.d} fill={path.fill} key={index} />
      ))}
    </svg>
  );
}
