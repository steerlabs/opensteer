/** One catalog-derived contract table compiled by the Mac helper and iPhone pod. */
import { mkdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { getIntegrationDefinition } from "../packages/integration-catalog/src/index.js";
import { isComputerAppDefinition } from "../packages/integration-core/src/computer-app.js";
import { computerAppOperationContract } from "../packages/integration-core/src/computer-app-tools.js";
import { computerUseDataApps, iphoneDataAppIds } from "../packages/protocol/src/computer-use.js";

const output = path.resolve(
  fileURLToPath(
    new URL(
      "../packages/apple-data/Sources/OpensteerAppleData/Resources/contracts.json",
      import.meta.url,
    ),
  ),
);

export async function generateAppleDataContracts(): Promise<void> {
  const apps = Object.entries(computerUseDataApps).map(([definitionId, grant]) => {
    const definition = getIntegrationDefinition(definitionId);
    if (!definition || !isComputerAppDefinition(definition)) {
      throw new Error(
        `The Apple data package serves ${definitionId}, which the catalog has no computer app for`,
      );
    }
    return {
      definitionId,
      grant,
      operations: definition.config.operations.map((operation) => ({
        contract: computerAppOperationContract(operation),
        effect: operation.effect,
        name: operation.name,
      })),
    };
  });
  await rm(
    new URL(
      "../packages/apple-data/Sources/OpensteerAppleData/DataContracts.generated.swift",
      import.meta.url,
    ),
    { force: true },
  );
  await mkdir(path.dirname(output), { recursive: true });
  const table =
    JSON.stringify(
      {
        grants: Object.fromEntries(apps.map(({ definitionId, grant }) => [definitionId, grant])),
        operations: Object.fromEntries(
          apps.map(({ definitionId, operations }) => [
            definitionId,
            Object.fromEntries(
              operations.map(({ name, contract, effect }) => [name, { contract, effect }]),
            ),
          ]),
        ),
      },
      null,
      2,
    ) + "\n";
  await writeFile(output, table);
  // CocoaPods compiles the iPhone pod without SwiftPM's generated resource accessors,
  // so every build embeds the same bytes through Swift source.
  await writeFile(
    new URL(
      "../packages/apple-data/Sources/OpensteerAppleData/ContractTable.generated.swift",
      import.meta.url,
    ),
    "// Generated by scripts/generate-apple-data-contracts.ts. Do not edit.\n" +
      `enum ContractTable {\n  static let json = #"""\n${table}"""#\n}\n`,
    { encoding: "utf8", mode: 0o644 },
  );
  const iphoneOperations = iphoneDataAppIds
    .map((id) => {
      const definition = getIntegrationDefinition(id);
      if (!definition || !isComputerAppDefinition(definition))
        throw new Error(`Missing iPhone definition: ${id}`);
      return (
        `    ${JSON.stringify(id)}: [\n` +
        definition.config.operations
          .map(
            (operation) =>
              `      ${JSON.stringify(operation.name)}: DataOperationContract(contract: ${JSON.stringify(computerAppOperationContract(operation))}, effect: .${operation.effect}),\n`,
          )
          .join("") +
        "    ],\n"
      );
    })
    .join("");
  await writeFile(
    new URL(
      "../apps/mobile/modules/iphone-apps/ios/Sources/IphoneAppsCore/IphoneContracts.generated.swift",
      import.meta.url,
    ),
    "// Generated by scripts/generate-apple-data-contracts.ts. Do not edit.\n" +
      "import OpensteerAppleData\n\npublic enum IphoneContracts {\n" +
      `  public static let operations: [String: [String: DataOperationContract]] = [\n${iphoneOperations}  ]\n}\n`,
    { encoding: "utf8", mode: 0o644 },
  );
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await generateAppleDataContracts();
}
