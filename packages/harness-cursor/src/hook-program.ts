/**
 * The program Cursor runs for every gated tool call.
 *
 * It is written into the session's plugin directory rather than shipped as a
 * file beside this source, because the Runner is bundled: there is no
 * package directory on disk at runtime to point `hooks.json` at. Cursor
 * executes the `command` string through a shell and delivers the hook payload
 * on stdin (`@anysphere/hooks`: `<command> <<'CURSOR_HOOK_EOF'…`), so this is
 * an ordinary stdin-to-stdout filter that happens to ask the Runner what to
 * answer.
 *
 * Everything it can fail at answers `deny`: a hook that prints nothing, exits
 * non-zero, or prints something unparseable is a blocked tool call anyway
 * under `failClosed` (cursor-facts §A.6), and denying with our own sentence
 * tells the model and the reader why instead of leaving Cursor to invent one.
 * `ask` is never printed: print mode has no client that could answer it.
 */
export const cursorHookProgramFileName = "opensteer-hook.mjs";

export const cursorHookProgramSource = `// Generated by Opensteer. Talks to the Run's approval socket and prints Cursor's verdict.
import { connect } from "node:net";

const socketPath = process.argv[2];
const maximumPayloadBytes = ${8 * 1_024 * 1_024};
let printed = false;

function print(verdict) {
  if (printed) return;
  printed = true;
  process.stdout.write(JSON.stringify(verdict));
  process.stdout.write("\\n");
}

function deny(reason) {
  print({
    permission: "deny",
    user_message: reason,
    agent_message: "Opensteer could not obtain approval for this tool call: " + reason,
  });
  process.exitCode = 0;
  process.exit(0);
}

if (typeof socketPath !== "string" || socketPath.length === 0) {
  deny("the approval socket was not configured");
}

let payload = "";
let payloadBytes = 0;
process.stdin.setEncoding("utf8");
process.stdin.on("error", () => deny("the hook payload could not be read"));
process.stdin.on("data", (chunk) => {
  payloadBytes += Buffer.byteLength(chunk, "utf8");
  if (payloadBytes > maximumPayloadBytes) deny("the hook payload was too large");
  payload += chunk;
});
process.stdin.on("end", () => {
  const socket = connect(socketPath);
  socket.setEncoding("utf8");
  let answer = "";
  socket.on("error", () => deny("the Opensteer Run is no longer accepting approvals"));
  socket.on("connect", () => {
    socket.write(payload.replace(/[\\r\\n]+/g, " ") + "\\n");
  });
  socket.on("data", (chunk) => {
    answer += chunk;
    const newline = answer.indexOf("\\n");
    if (newline < 0) {
      if (answer.length > maximumPayloadBytes) deny("the approval answer was too large");
      return;
    }
    let verdict;
    try {
      verdict = JSON.parse(answer.slice(0, newline));
    } catch {
      deny("the approval answer could not be read");
      return;
    }
    socket.end();
    if (verdict && verdict.permission === "allow") {
      print({ permission: "allow" });
      process.exit(0);
    }
    print({
      permission: "deny",
      user_message: typeof verdict?.user_message === "string" ? verdict.user_message : "denied",
      agent_message:
        typeof verdict?.agent_message === "string"
          ? verdict.agent_message
          : "The person denied this tool call in Opensteer.",
    });
    process.exit(0);
  });
  socket.on("close", () => deny("the Opensteer Run ended before this was approved"));
});
`;
