/**
 * The integrations this tree ships artwork for.
 *
 * An app on a computer has no icon URL to fetch — it is the product's own mark,
 * and asking a Host or a third party for it at render time would make a
 * person's integrations page describe them to somebody else. The bytes live in
 * `packages/client/assets/integrations`, and each client binds this id to its
 * own bundle so there is one list and no per-surface guess about which
 * integrations have a mark.
 */
export const bundledIntegrationIconIds = ["apple-messages"] as const;

export type BundledIntegrationIconId = (typeof bundledIntegrationIconIds)[number];

export function bundledIntegrationIcon(definitionId: string): BundledIntegrationIconId | null {
  return (
    bundledIntegrationIconIds.find(
      (candidate): candidate is BundledIntegrationIconId => candidate === definitionId,
    ) ?? null
  );
}

/**
 * How one integration is drawn: artwork this tree ships, a brand's own vector
 * mark, a system glyph for an app on the person's device, or nothing, which a
 * client draws as initials.
 *
 * Marks are data rather than files so web and the phone draw the same shape
 * from one table, with no request and no bundler asset per mark. Each is one
 * 24×24 path in its brand colour, drawn on a light tile.
 */
export type IntegrationMark =
  | { readonly kind: "art"; readonly art: BundledIntegrationIconId }
  | { readonly kind: "brand"; readonly color: string; readonly d: string }
  | { readonly kind: "glyph"; readonly color: string; readonly d: string };

export function integrationMark(definitionId: string): IntegrationMark | null {
  const art = bundledIntegrationIcon(definitionId);
  if (art) return { kind: "art", art };
  const glyph = deviceGlyphs[definitionId];
  if (glyph) return { kind: "glyph", ...glyph };
  const brand = brandOf[definitionId];
  return brand ? { kind: "brand", ...brands[brand] } : null;
}

