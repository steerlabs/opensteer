import { OpensteerError } from "@opensteer/core";
import { readFile } from "node:fs/promises";
import { dirname, isAbsolute, join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { z } from "zod";

/** The generated sign-in program, written into the isolated profile's own state. */
export const piLoginScriptFileName = "opensteer-login.mjs";

/** One line the sign-in child writes on stdout. Nothing else crosses. */
export const PiLoginMessageSchema = z.discriminatedUnion("type", [
  z.object({
    type: z.literal("device_code"),
    userCode: z.string().min(1).max(255),
    verificationUrl: z.string().min(1).max(2_048),
  }),
  z.object({ type: z.literal("ready") }),
  z.object({ detail: z.string().max(2_000), type: z.literal("failed") }),
]);

export type PiLoginMessage = z.infer<typeof PiLoginMessageSchema>;

/**
 * Pi's device-code sign-in, as a program the Runner starts and never links.
 *
 * Pi has no `login` command and no RPC login — `/login` is TUI-only and
 * `pi auth` can only check (pi-facts §4) — so the only programmatic entry is
 * `ModelRuntime.login(providerId, "oauth", interaction)` from the package
 * itself. That package is a 400 MB agent runtime the Runner has no other reason
 * to load, and the packaged Personal runtime ships the Runner as one bundled
 * file, so it is imported here instead: in a child process, by absolute file
 * URL, with `PI_CODING_AGENT_DIR` pointing at the isolated profile so Pi writes
 * its own 0600 `auth.json` exactly where the rest of this driver reads it.
 *
 * Measured against 0.85.1: xAI asks nothing and notifies `device_code`; GitHub
 * Copilot asks one `text` prompt for an Enterprise domain (blank is
 * github.com); OpenAI Codex asks a `select` whose answer must be the option's
 * **id** (`"device_code"`), never its label.
 */
export function piLoginScriptSource(): string {
  return `// Generated by Opensteer. Signs one provider in with a device code and exits.
const [entryUrl, provider] = process.argv.slice(2);

function emit(message) {
  process.stdout.write(JSON.stringify(message) + "\\n");
}

async function main() {
  const { ModelRuntime } = await import(entryUrl);
  const runtime = await ModelRuntime.create({ modelsPath: null, refreshOnCreate: false });
  await runtime.login(provider, "oauth", {
    notify: (event) => {
      if (event.type !== "device_code") return;
      emit({ type: "device_code", userCode: event.userCode, verificationUrl: event.verificationUri });
    },
    prompt: async (prompt) => {
      // GitHub Copilot's only prompt asks for an optional Enterprise domain;
      // blank means github.com.
      if (prompt.type !== "select") return "";
      const option = (prompt.options ?? []).find((candidate) => /device.?code/i.test(candidate.id));
      if (!option) throw new Error("Pi offers no headless sign-in for " + provider);
      return option.id;
    },
  });
}

main().then(
  () => {
    emit({ type: "ready" });
    process.exit(0);
  },
  (error) => {
    emit({ type: "failed", detail: String(error && error.message ? error.message : error).slice(0, 2000) });
    process.exit(1);
  },
);
`;
}

const PiPackageSchema = z.looseObject({
  exports: z.looseObject({
    ".": z.looseObject({ import: z.string().min(1) }),
  }),
  name: z.literal("@earendil-works/pi-coding-agent"),
});

/**
 * The package's own module entry, found from the RPC script the Runner was
 * given. The path is walked up rather than computed from the catalog's layout,
 * so a packager that stages the tree differently does not silently produce a
 * wrong URL, and the entry comes from the package's own `exports` map rather
 * than being guessed.
 */
export async function piPackageEntryUrl(executable: string): Promise<string> {
  let directory = dirname(resolve(executable));
  for (let depth = 0; depth < 8; depth += 1) {
    const manifestPath = join(directory, "package.json");
    const parsed = PiPackageSchema.safeParse(await readJson(manifestPath));
    if (parsed.success) {
      const entry = parsed.data.exports["."].import;
      if (isAbsolute(entry)) return pathToFileURL(entry).href;
      return pathToFileURL(resolve(directory, entry)).href;
    }
    const parent = dirname(directory);
    if (parent === directory) break;
    directory = parent;
  }
  throw new OpensteerError({
    code: "harness_error",
    message: `The Pi package could not be found next to ${executable}`,
  });
}

async function readJson(path: string): Promise<unknown> {
  try {
    return JSON.parse(await readFile(path, "utf8"));
  } catch {
    return undefined;
  }
}
