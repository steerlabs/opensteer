import { z } from "zod";

/**
 * On-device dictation into the message composer: the one contract every
 * platform implements and the composer controller consumes. Apple's
 * SpeechAnalyzer recognizes speech in a native process on the person's own
 * Mac or iPhone; audio never leaves that process, and only text, an input
 * level and the session's lifecycle cross into JavaScript. No Host is
 * involved. See docs/dictation.md.
 */

/**
 * Lengths are UTF-16 code units: what JavaScript's `length` and text fields
 * report, and what the Swift encoder checks with `utf16.count`. Zod's string
 * `max` counts code points instead, so the bound is checked on `length`.
 * Ten minutes of speech stays far below either bound, so reaching one is a
 * failure rather than something to truncate.
 */
export const dictationTextMaxLength = 50_000;
export const dictationSegmentsMaxCount = 1_000;

const DictationTextSchema = z.string().refine((text) => text.length <= dictationTextMaxLength, {
  message: `Dictation text is at most ${dictationTextMaxLength} UTF-16 code units.`,
});

/**
 * A canonical lowercase UUID v4, generated by the controller. Native code
 * echoes it byte for byte; a session that comes back in another case or
 * version was re-encoded through a platform UUID type, which is a bug.
 */
export const DictationSessionIdSchema = z
  .string()
  .regex(/^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/u);
export type DictationSessionId = z.infer<typeof DictationSessionIdSchema>;

/** Per session, starting at 1 and rising by exactly 1, so a gap is detectable. */
export const DictationSeqSchema = z.number().int().positive().max(Number.MAX_SAFE_INTEGER);

/**
 * Why the microphone button is absent. `restricted` is device policy, which
 * the person cannot change; a denied microphone stays available because
 * Settings can fix it.
 */
export const DictationUnavailableReasonSchema = z.enum([
  "platform",
  "os",
  "hardware",
  "language",
  "restricted",
]);
export type DictationUnavailableReason = z.infer<typeof DictationUnavailableReasonSchema>;

export const DictationMicrophoneSchema = z.enum(["undetermined", "granted", "denied"]);
export type DictationMicrophone = z.infer<typeof DictationMicrophoneSchema>;

export const DictationAvailabilitySchema = z.discriminatedUnion("available", [
  z.strictObject({
    available: z.literal(false),
    reason: DictationUnavailableReasonSchema,
  }),
  z.strictObject({
    available: z.literal(true),
    /** The language Apple resolved from the system's preferred languages, e.g. `en-US`. */
    locale: z.string().min(2).max(35),
    /** Its short display name, e.g. `English`. */
    languageName: z.string().min(1).max(100),
    /** `download` until this language's on-device model is installed. */
    model: z.enum(["installed", "download"]),
    microphone: DictationMicrophoneSchema,
  }),
]);
export type DictationAvailability = z.infer<typeof DictationAvailabilitySchema>;

export const DictationErrorSchema = z.enum([
  /** The microphone is denied for this app. */
  "permission-denied",
  /** Another dictation session is active in this app, for example in another window. */
  "busy",
  /** Capture could not start or continue: no input device, or the audio engine failed. */
  "microphone-unavailable",
  /** The language's model is not installed, or the language is no longer supported. */
  "model-unavailable",
  /** Offline, out of storage, out of language reservations, or installation failed. */
  "download-failed",
  /** Recognition failed, audio overran its bound, finalization timed out, or events were lost. */
  "recognition-failed",
  /** The native service could not launch, crashed, or broke this contract. */
  "service-unavailable",
]);
export type DictationError = z.infer<typeof DictationErrorSchema>;

export const DictationEndReasonSchema = z.enum([
  /** Capture: stopped and finalized. Download: installed. */
  "completed",
  "cancelled",
  /** A call, Siri, an alarm, a media reset, the app leaving the foreground, or sleep. */
  "interrupted",
  /** The audio input route changed while capturing. */
  "device-changed",
  /** `error` says why. */
  "failed",
]);
export type DictationEndReason = z.infer<typeof DictationEndReasonSchema>;

const DictationSegmentsSchema = z.array(DictationTextSchema).max(dictationSegmentsMaxCount);

export const DictationEventSchema = z.discriminatedUnion("type", [
  z.strictObject({
    type: z.literal("downloading"),
    session: DictationSessionIdSchema,
    seq: DictationSeqSchema,
    /** Fraction installed, or null while the system cannot say. */
    progress: z.number().min(0).max(1).nullable(),
  }),
  z.strictObject({
    type: z.literal("listening"),
    session: DictationSessionIdSchema,
    seq: DictationSeqSchema,
  }),
  z.strictObject({
    type: z.literal("text"),
    session: DictationSessionIdSchema,
    seq: DictationSeqSchema,
    /** Segments that became final since the previous text event, in audio order. */
    finalized: DictationSegmentsSchema,
    /** Every still-tentative segment, in audio order; it replaces the previous tail. */
    volatile: DictationSegmentsSchema,
  }),
  z.strictObject({
    type: z.literal("level"),
    session: DictationSessionIdSchema,
    seq: DictationSeqSchema,
    level: z.number().min(0).max(1),
  }),
  z
    .strictObject({
      type: z.literal("ended"),
      session: DictationSessionIdSchema,
      seq: DictationSeqSchema,
      reason: DictationEndReasonSchema,
      /** Present and non-null exactly when `reason` is `failed`. */
      error: DictationErrorSchema.nullable(),
    })
    .refine((event) => (event.reason === "failed") === (event.error !== null), {
      message: "A dictation ends with an error exactly when it failed.",
      path: ["error"],
    }),
]);
export type DictationEvent = z.infer<typeof DictationEventSchema>;

/** The session a command addresses, as it crosses a process boundary. */
export const DictationSessionInputSchema = z.strictObject({
  session: DictationSessionIdSchema,
});
export type DictationSessionInput = z.infer<typeof DictationSessionInputSchema>;

/**
 * What a platform provides. Command promises only acknowledge acceptance:
 * every outcome, including a start that cannot begin, arrives as exactly one
 * `ended` event for that session. A rejected promise means the transport
 * itself failed. `stop` and `cancel` for an unknown or finished session do
 * nothing; a `start` or `download` while another session is active ends the
 * new session `failed` with `busy`.
 */
export interface DictationPort {
  /** Never prompts, downloads or opens the microphone. */
  availability(): Promise<DictationAvailability>;
  /** Installs the resolved language's model; never opens the microphone. */
  download(session: DictationSessionId): Promise<void>;
  /** Asks for the microphone if undetermined, then captures and recognizes. */
  start(session: DictationSessionId): Promise<void>;
  /** Stops capture, finalizes everything heard, then ends `completed`. */
  stop(session: DictationSessionId): Promise<void>;
  /** Stops everything now and discards it; ends `cancelled`. */
  cancel(session: DictationSessionId): Promise<void>;
  subscribe(listener: (event: DictationEvent) => void): () => void;
  openMicrophoneSettings(): Promise<void>;
}
